// Testa o banner de cookies e o bloqueio do GA4 antes do aceite (Etapa 11).
// Uso: servidor em :4180; node scripts/teste-cookies.mjs. Para testar o GA4: build com NEXT_PUBLIC_GA4_ID=G-TESTE00000 e COM_GA=1 node scripts/teste-cookies.mjs
import { chromium } from "playwright-core";
const base = process.env.BASE || "http://localhost:4180";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
const r = [];
const ok = (t, c, d = "") => r.push({ teste: t, resultado: c ? "OK" : "FALHA", detalhe: String(d).slice(0, 70) });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 } });
const terceiros = [];
ctx.on("request", (q) => { const u = new URL(q.url()); if (!["localhost", "127.0.0.1"].includes(u.hostname)) terceiros.push(u.hostname); });
await ctx.route(/googletagmanager|google-analytics/, (rt) => rt.fulfill({ status: 200, contentType: "text/javascript", body: "" }));
const p = await ctx.newPage();
await p.goto(base + "/", { waitUntil: "networkidle" });
await p.waitForTimeout(800);
ok("Banner aparece na primeira visita", await p.locator(".banner-cookies").isVisible());
const [rec, ace] = await Promise.all([p.locator(".banner-cookies button", { hasText: "Recusar" }), p.locator(".banner-cookies button", { hasText: "Aceitar" })]);
const br = await rec.boundingBox(), ba = await ace.boundingBox();
const estilo = (l) => l.evaluate((e) => { const s = getComputedStyle(e); return [s.backgroundColor, s.color, s.borderColor, s.fontSize, s.fontWeight].join("|"); });
ok("Aceitar e Recusar no mesmo nível (tamanho e estilo)", Math.abs(br.width - ba.width) < 2 && Math.abs(br.height - ba.height) < 1 && (await estilo(rec)) === (await estilo(ace)));
ok("Nenhum terceiro carrega antes do aceite", terceiros.length === 0, [...new Set(terceiros)].join(", "));
await rec.click();
await p.waitForTimeout(500);
ok("Recusar fecha o banner", !(await p.locator(".banner-cookies").count()));
await p.reload({ waitUntil: "networkidle" }); await p.waitForTimeout(600);
ok("Recusa é lembrada (sem banner) e nada carrega", !(await p.locator(".banner-cookies").count()) && terceiros.length === 0, [...new Set(terceiros)].join(", "));
await p.locator("footer button", { hasText: "Gerenciar cookies" }).click();
await p.waitForTimeout(400);
ok("“Gerenciar cookies” reabre o banner", await p.locator(".banner-cookies").isVisible());
await p.locator(".banner-cookies button", { hasText: "Aceitar" }).click();
await p.waitForTimeout(1500);
if (process.env.COM_GA) ok("GA4 só carrega depois do aceite", terceiros.some((h) => /googletagmanager/.test(h)), [...new Set(terceiros)].join(", "));
else r.push({ teste: "GA4 depois do aceite", resultado: "—", detalhe: "build sem NEXT_PUBLIC_GA4_ID (rode com COM_GA=1 num build com ID de teste)" });
await p.goto(base + "/privacidade/", { waitUntil: "networkidle" });
await p.locator("main button", { hasText: "Gerenciar cookies" }).click();
await p.waitForTimeout(300);
ok("Botão da política também reabre o banner", await p.locator(".banner-cookies").isVisible());
await ctx.close(); await browser.close();
console.table(r);
console.log(r.every((x) => x.resultado !== "FALHA") ? "TODOS OK" : "HÁ FALHAS");
